    public void initialiserCollisions() {
        collisionTiles.clear();
        for (int y = 0; y < map.length; y++) {
            for (int x = 0; x < map[y].length; x++) {
                if (estTuilleSolide(map[y][x]) ) {
                    collisionTiles.add(new Hitbox(x * tileSize, y * tileSize, tileSize, tileSize));
                }
            }
        }
    }

    public void mettreAJourCollisionTuile(int x, int y){
        double posX = x * 32;
        double posY = y * 32;
        int i = 0;
        boolean trouvee = false;

        while (i < collisionTiles.size() && !trouvee){
            Hitbox hitbox = collisionTiles.get(i);
            if(hitbox.couvreTuile(x, y)){
                collisionTiles.remove(i);
                trouvee = true;
            }
            i++;
        }

        if(map[y][x] != 0){
            collisionTiles.add(new Hitbox(posX,posY, tileSize, tileSize));
        }
    }

    public boolean checkCollision(Hitbox hitbox) {
        for (Hitbox tile : collisionTiles) {
            if (tile.colision(hitbox)) {
                return true;
            }
        }
        return false;
    }
